#!/bin/sh
# Startup script for the combined pokedex-tracker container.
# 1. Writes the trusted-proxy list for nginx if TRUSTED_PROXIES is set.
# 2. Starts the sync API server in the background on port 3001, and starts it
#    again if it ever exits (nginx is PID 1, so Docker's restart policy would
#    not notice the sync server dying on its own).
# 3. Execs nginx in the foreground (PID 1).
#
# Auth is handled in the React app (custom login screen) — no nginx Basic Auth.
# The SYNC_TOKEN is stored in the user's browser localStorage after first login.
set -e

# ── Trusted proxies ────────────────────────────────────────────────────────────
# The image ships a default (loopback + private ranges; see deploy/nginx/real-ip.conf).
# TRUSTED_PROXIES replaces it: comma-separated addresses or CIDR ranges, or
# "none" to take every connection's own address as the client.
REAL_IP_CONF=/etc/nginx/pokedex-real-ip.conf
if [ -n "${TRUSTED_PROXIES:-}" ]; then
  # Any failure here keeps the default the image ships with; it never stops the container
  DEFAULT_COPY=/tmp/pokedex-real-ip.default
  GENERATED=/tmp/pokedex-real-ip.generated
  if cp "$REAL_IP_CONF" "$DEFAULT_COPY"; then
    accepted=0
    echo "# Generated by docker-entrypoint.sh from TRUSTED_PROXIES" > "$GENERATED"
    if [ "$TRUSTED_PROXIES" != "none" ]; then
      set -f   # no filename expansion while the list is split
      for range in $(printf '%s' "$TRUSTED_PROXIES" | tr ',' ' '); do
        case "$range" in
          # Addresses and CIDR ranges only: nothing that could add other directives
          *[!0-9a-fA-F:./]*) echo "[entrypoint] TRUSTED_PROXIES: ignoring \"$range\"" >&2 ;;
          *) echo "set_real_ip_from $range;" >> "$GENERATED"; accepted=$((accepted + 1)) ;;
        esac
      done
      set +f
      echo "real_ip_header X-Forwarded-For;" >> "$GENERATED"
      echo "real_ip_recursive on;" >> "$GENERATED"
    fi
    if [ "$TRUSTED_PROXIES" != "none" ] && [ "$accepted" -eq 0 ]; then
      echo "[entrypoint] TRUSTED_PROXIES has no usable address — using the default instead" >&2
    elif cp "$GENERATED" "$REAL_IP_CONF" && nginx -t -q; then
      :
    else
      echo "[entrypoint] TRUSTED_PROXIES=\"$TRUSTED_PROXIES\" could not be applied — using the default instead" >&2
      cp "$DEFAULT_COPY" "$REAL_IP_CONF" || true
    fi
  fi
fi

# ── Sync server ────────────────────────────────────────────────────────────────
# Runs as the unprivileged `node` user. /data may come from an older image (files
# owned by root) or from a host path, so it is handed to `node` first; where that
# isn't possible (a host path the container may not chown, root-squashed NFS, …)
# the server runs as root as before, rather than not being able to save.
RUN_AS=""
if chown -R node:node /data 2>/dev/null \
  && su-exec node test -w /data \
  && { [ ! -d /data/snapshots ] || su-exec node test -w /data/snapshots; } \
  && { [ ! -e /data/sync.json ] || su-exec node test -r /data/sync.json; }; then
  RUN_AS="su-exec node"
else
  echo "[entrypoint] /data can't be handed to the node user — running the sync server as root" >&2
fi

(
  while true; do
    # $RUN_AS is empty or "su-exec node": word splitting is wanted here
    # shellcheck disable=SC2086
    SYNC_TOKEN="${SYNC_TOKEN:-}" DATA_DIR="/data" $RUN_AS node /sync-server/server.js || true
    echo "[entrypoint] sync server exited — restarting in 2s" >&2
    sleep 2
  done
) &

# ── Hand off to nginx (CMD argument) ──────────────────────────────────────────
exec "$@"
